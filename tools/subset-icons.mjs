// Rebuilds assets/fonts/remixicon.{woff2,css} with only the Remix Icon glyphs
// the site actually uses (any `ri-*` class in the HTML/JS). The full font is
// ~165 KB plus ~140 KB of CSS; the subset is a few KB.
//
// Run after adding or removing an icon:
//   npm install --no-save --no-package-lock subset-font@2   (once; node_modules is gitignored)
//   node tools/subset-icons.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "4.3.0";
const CDN = `https://cdn.jsdelivr.net/npm/remixicon@${VERSION}/fonts`;
const root = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(import.meta.url);

let subsetFont;
try {
  subsetFont = require("subset-font");
} catch {
  console.error("Missing dependency. Run: npm install --no-save --no-package-lock subset-font@2");
  process.exit(1);
}

// 1. Collect icon names used in the site's own files.
const SKIP = new Set(["node_modules", ".git", "netlify", "tools", "assets"]);
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".") || SKIP.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(html|js)$/.test(name)) files.push(p);
  }
})(root);
const used = new Set();
for (const f of files) for (const m of readFileSync(f, "utf8").matchAll(/\bri-[a-z0-9-]+-(?:line|fill)\b/g)) used.add(m[0]);

// 2. Map names to code points from the upstream stylesheet.
const css = await (await fetch(`${CDN}/remixicon.css`)).text();
const codes = new Map();
for (const m of css.matchAll(/\.(ri-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";/g)) codes.set(m[1], m[2]);
const missing = [...used].filter((n) => !codes.has(n));
if (missing.length) {
  console.error(`Unknown icon(s) in Remix Icon ${VERSION}: ${missing.join(", ")}`);
  process.exit(1);
}
const names = [...used].sort();

// 3. Subset the font to those glyphs.
const font = Buffer.from(await (await fetch(`${CDN}/remixicon.woff2`)).arrayBuffer());
const text = names.map((n) => String.fromCodePoint(parseInt(codes.get(n), 16))).join("");
const subset = await subsetFont(font, text, { targetFormat: "woff2" });
writeFileSync(join(root, "assets/fonts/remixicon.woff2"), subset);

// 4. Write a matching minimal stylesheet.
const out = `/* Remix Icon ${VERSION} (Apache-2.0, https://remixicon.com), subset to the icons this site uses.
   Generated by tools/subset-icons.mjs. Do not edit by hand. */
@font-face {
  font-family: "remixicon";
  src: url("remixicon.woff2") format("woff2");
  font-display: block;
}

[class^="ri-"],
[class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${names.map((n) => `.${n}:before { content: "\\${codes.get(n)}"; }`).join("\n")}
`;
writeFileSync(join(root, "assets/fonts/remixicon.css"), out);
console.log(`${names.length} icons from ${files.length} files → ${subset.length} bytes`);
console.log(files.map((f) => "  " + relative(root, f)).join("\n"));
